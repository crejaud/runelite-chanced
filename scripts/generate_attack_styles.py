#!/usr/bin/env python3
"""Generate attack_styles.txt from RuneLite's named gameval IDs.

Reads the constant names of net.runelite.api.gameval.AnimationID and SpotanimID
(via javap on the runelite-api jar) and tags each NPC attack animation and
projectile with the attack style its name implies.

The output is plain numeric data bundled with the plugin, so RuneLite renaming a gameval
constant can never break the build. Running this is optional: do it when shipping an update
anyway, to pick up attacks added to the game since the last snapshot. Ids missing from the
snapshot fall back to the NPC's wiki attack styles.

Usage:
    ./gradlew build --refresh-dependencies   # download the latest RuneLite release
    python scripts/generate_attack_styles.py [path/to/runelite-api-<version>.jar]

Without a path, uses the newest runelite-api jar in the Gradle cache.
"""
import os
import re
import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src/main/resources/com/crejaud/chanced/attack_styles.txt"

CONST = re.compile(r"public static final int (\w+) = (-?\d+);")

# Order matters: the first matching rule wins.
ANIM_RULES = [
    ("SPECIAL", re.compile(r"SPECIAL|_SPEC_|_SPEC$|STOMP")),
    ("MAGIC", re.compile(r"MAGIC|MAGE|SPELL|_CAST")),
    ("RANGED", re.compile(r"RANGED|_RANGE|ARROW|THROW|SHOOT|_BOW")),
    ("MELEE", re.compile(r"MELEE|STAB|SLASH|CRUSH|PUNCH|BITE|CLAW|SWIPE")),
]
PROJ_RULES = [
    ("MAGIC", re.compile(r"MAGIC|MAGE|SPELL|(WIND|WATER|EARTH|FIRE)_(STRIKE|BOLT|BLAST|WAVE|SURGE)")),
    ("RANGED", re.compile(r"RANGED|_RANGE|ARROW|BOLT|DART|KNIFE|JAVELIN|THROWN|SPEAR|CHINCHOMPA")),
]
ATTACK = re.compile(r"ATTACK|_ATK")
PROJECTILE = re.compile(r"_PROJ|TRAVEL")
# Player and object animations are not NPC attacks.
SKIP = re.compile(r"^(HUMAN|PLAYER|BR_|SKILL|EMOTE|QIP)")


def constants(jar, cls):
    out = subprocess.run(["javap", "-cp", jar, "-constants", cls], capture_output=True, text=True, check=True).stdout
    return [(name, int(value)) for name, value in CONST.findall(out)]


def tag(name, rules):
    for style, rule in rules:
        if rule.search(name):
            return style
    return None


def version_key(path):
    version = path.parent.parent.name
    return [int(p) if p.isdigit() else 0 for p in re.split(r"[.-]", version)]


def find_jar():
    gradle_home = Path(os.environ.get("GRADLE_USER_HOME", Path.home() / ".gradle"))
    cache = gradle_home / "caches/modules-2/files-2.1/net.runelite/runelite-api"
    jars = [j for j in cache.glob("*/*/runelite-api-*.jar") if "sources" not in j.name]
    if not jars:
        sys.exit(f"No runelite-api jar under {cache}; run ./gradlew build first")
    return str(max(jars, key=version_key))


def main():
    jar = sys.argv[1] if len(sys.argv) > 1 else find_jar()
    print(f"Using {jar}")
    anims = {}
    for name, value in constants(jar, "net.runelite.api.gameval.AnimationID"):
        if SKIP.search(name) or not ATTACK.search(name):
            continue
        anims.setdefault(value, (tag(name, ANIM_RULES) or "UNKNOWN", name))
    projs = {}
    for name, value in constants(jar, "net.runelite.api.gameval.SpotanimID"):
        if not PROJECTILE.search(name):
            continue
        style = tag(name, PROJ_RULES)
        if style:
            projs.setdefault(value, (style, name))

    lines = [
        "# Attack style implied by NPC attack animation and projectile names in RuneLite's gameval IDs.",
        "# Generated by scripts/generate_attack_styles.py; do not edit by hand.",
        "# kind id style name",
    ]
    lines += [f"a {i} {s} {n}" for i, (s, n) in sorted(anims.items())]
    lines += [f"p {i} {s} {n}" for i, (s, n) in sorted(projs.items())]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    tagged = sum(1 for s, _ in anims.values() if s != "UNKNOWN")
    print(f"{len(anims)} attack animations ({tagged} with a style), {len(projs)} projectiles -> {OUT}")


if __name__ == "__main__":
    main()
