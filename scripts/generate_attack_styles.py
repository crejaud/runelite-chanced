#!/usr/bin/env python3
"""Generate AttackStyleTable.java from RuneLite's named gameval IDs.

Reads the constant names of net.runelite.api.gameval.AnimationID and SpotanimID
(via javap on the runelite-api jar) and tags each NPC attack animation and
projectile with the attack style its name implies.

Usage:
    python scripts/generate_attack_styles.py path/to/runelite-api-<version>.jar

Re-run after a RuneLite update renames or adds gameval IDs.
"""
import re
import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src/main/java/com/crejaud/chanced/AttackStyleTable.java"

CONST = re.compile(r"public static final int (\w+) = (-?\d+);")

# Order matters: the first matching rule wins.
ANIM_RULES = [
    ("SPECIAL", re.compile(r"SPECIAL|_SPEC_|_SPEC$|STOMP")),
    ("MAGIC", re.compile(r"MAGIC|MAGE|SPELL|_CAST")),
    ("RANGED", re.compile(r"RANGED|_RANGE|ARROW|THROW|SHOOT|_BOW")),
    ("MELEE", re.compile(r"MELEE|STAB|SLASH|CRUSH|PUNCH|BITE|CLAW|SWIPE")),
]
PROJ_RULES = [
    ("MAGIC", re.compile(r"MAGIC|MAGE|SPELL|(WIND|WATER|EARTH|FIRE)_(STRIKE|BOLT|BLAST|WAVE|SURGE)")),
    ("RANGED", re.compile(r"RANGED|_RANGE|ARROW|BOLT|DART|KNIFE|JAVELIN|THROWN|SPEAR|CHINCHOMPA")),
]
ATTACK = re.compile(r"ATTACK|_ATK")
PROJECTILE = re.compile(r"_PROJ|TRAVEL")
# Player and object animations are not NPC attacks.
SKIP = re.compile(r"^(HUMAN|PLAYER|BR_|SKILL|EMOTE|QIP)")


def constants(jar, cls):
    out = subprocess.run(["javap", "-cp", jar, "-constants", cls], capture_output=True, text=True, check=True).stdout
    return CONST.findall(out)


def tag(name, rules):
    for style, rule in rules:
        if rule.search(name):
            return style
    return None


def main():
    jar = sys.argv[1]
    anims = []
    for name, _ in constants(jar, "net.runelite.api.gameval.AnimationID"):
        if SKIP.search(name) or not ATTACK.search(name):
            continue
        anims.append((name, tag(name, ANIM_RULES) or "UNKNOWN"))
    projs = []
    for name, _ in constants(jar, "net.runelite.api.gameval.SpotanimID"):
        if not PROJECTILE.search(name):
            continue
        style = tag(name, PROJ_RULES)
        if style:
            projs.append((name, style))

    lines = [
        "package com.crejaud.chanced;",
        "",
        "import java.util.HashMap;",
        "import java.util.Map;",
        "import net.runelite.api.gameval.AnimationID;",
        "import net.runelite.api.gameval.SpotanimID;",
        "",
        "/**",
        " * Attack style implied by each NPC attack animation and projectile name.",
        " * Generated by scripts/generate_attack_styles.py; do not edit by hand.",
        " */",
        "final class AttackStyleTable",
        "{",
        "\tprivate static final Map<Integer, AttackHint> ANIMATIONS = new HashMap<>();",
        "\tprivate static final Map<Integer, AttackStyle> PROJECTILES = new HashMap<>();",
        "",
        "\tprivate AttackStyleTable()",
        "\t{",
        "\t}",
        "",
        "\t/** Hint for an attack animation, or null when the animation is not an attack. */",
        "\tstatic AttackHint animation(int id)",
        "\t{",
        "\t\treturn ANIMATIONS.get(id);",
        "\t}",
        "",
        "\t/** Style of a projectile, or null when its name does not say. */",
        "\tstatic AttackStyle projectile(int id)",
        "\t{",
        "\t\treturn PROJECTILES.get(id);",
        "\t}",
        "",
        "\tstatic int animationCount()",
        "\t{",
        "\t\treturn ANIMATIONS.size();",
        "\t}",
        "",
        "\tstatic int projectileCount()",
        "\t{",
        "\t\treturn PROJECTILES.size();",
        "\t}",
        "",
    ]
    # Split puts across methods to stay far below the 64KB method limit.
    chunk = 400
    anim_chunks = [anims[i:i + chunk] for i in range(0, len(anims), chunk)]
    lines.append("\tstatic")
    lines.append("\t{")
    for i in range(len(anim_chunks)):
        lines.append(f"\t\tanimations{i}();")
    lines.append("\t\tprojectiles();")
    lines.append("\t}")
    for i, part in enumerate(anim_chunks):
        lines += ["", f"\tprivate static void animations{i}()", "\t{"]
        lines += [f"\t\tANIMATIONS.put(AnimationID.{n}, AttackHint.{s});" for n, s in part]
        lines.append("\t}")
    lines += ["", "\tprivate static void projectiles()", "\t{"]
    lines += [f"\t\tPROJECTILES.put(SpotanimID.{n}, AttackStyle.{s});" for n, s in projs]
    lines += ["\t}", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    tagged = sum(1 for _, s in anims if s != "UNKNOWN")
    print(f"{len(anims)} attack animations ({tagged} with a style), {len(projs)} projectiles -> {OUT}")


if __name__ == "__main__":
    main()
